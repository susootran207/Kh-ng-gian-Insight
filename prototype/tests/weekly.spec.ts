import {test,expect} from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import {resolve} from 'node:path'
import {mkdirSync} from 'node:fs'
const entry='/tests/weekly-harness/index.html', output=resolve('test-results-w1-evidence')
mkdirSync(output,{recursive:true})
const expected=['w1-fixture-beta','w1-fixture-alpha']
for(const width of [320,390,768,1440])test('W1 fixture consistency, keyboard and responsive '+width,async({page})=>{
  await page.setViewportSize({width,height:1000});await page.emulateMedia({reducedMotion:'reduce'})
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto(entry+'#/');await page.evaluate(()=>document.fonts.ready)
  await expect(page.locator('.weekly-copy h3')).toHaveText('Một khoảng dừng cùng trang sách')
  await expect(page.locator('.top-garland')).toHaveAttribute('data-variant','B')
  await expect(page.getByRole('button',{name:/Mây, chú mèo/})).toBeVisible()
  const open=page.getByRole('button',{name:'Mở một trang đọc'});await open.focus();await page.keyboard.press('Enter')
  const hrefs=await page.locator('#weekly-excerpt li a').evaluateAll(els=>els.map(el=>el.getAttribute('href')!.split('/').at(-1)))
  expect(hrefs).toEqual(expected);await expect(page.locator('#weekly-excerpt')).not.toContainText('chưa có quyền')
  await page.getByRole('button',{name:'Khép lại chuyên đề'}).click();await expect(page.locator('#weekly-excerpt')).toHaveCount(0)
  await page.locator('#chuyen-de').evaluate(el=>el.scrollIntoView({block:'start',behavior:'instant'}))
  await page.screenshot({path:output+'/weekly-home-'+width+'.jpg',type:'jpeg',quality:80})
  expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()).violations).toEqual([])
  await page.getByRole('link',{name:'Xem chuyên đề đầy đủ'}).click();await expect(page.locator('main')).toBeFocused()
  await expect(page.locator('h1')).toHaveText('Một khoảng dừng cùng trang sách')
  expect(await page.locator('.library-entry h2 a').evaluateAll(els=>els.map(el=>el.getAttribute('href')!.split('/').at(-1)))).toEqual(expected)
  await page.evaluate(()=>document.fonts.ready);await page.screenshot({path:output+'/weekly-detail-'+width+'.jpg',type:'jpeg',quality:80})
  expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()).violations).toEqual([])
  await page.getByRole('link',{name:'Tất cả chuyên đề',exact:false}).last().click()
  await expect(page.locator('.topic-spread')).toHaveCount(2)
  await expect(page.locator('.topic-spread h2').first()).toHaveText('Một khoảng dừng cùng trang sách')
  await expect(page.locator('main')).not.toContainText('Trang thử của tuần sau')
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));await page.screenshot({path:output+'/weekly-index-'+width+'.jpg',type:'jpeg',quality:80})
  expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()).violations).toEqual([])
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy()
  await page.goto(entry+'#/thu-vien?chuyen-de=w1-fixture-current')
  await expect(page.locator('.library-entry')).toHaveCount(2)
  await expect(page.getByRole('combobox',{name:'Chuyên đề tuần',exact:true})).toHaveValue('w1-fixture-current')
  await page.locator('.library-filters').scrollIntoViewIfNeeded();await page.screenshot({path:output+'/weekly-library-'+width+'.jpg',type:'jpeg',quality:80})
  expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()).violations).toEqual([])
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy()
  expect(errors).toEqual([])
})
